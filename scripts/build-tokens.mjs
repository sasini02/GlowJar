// Generates src/styles/tokens.css from design/tokens.json so the design file
// stays the single source of truth. Run with `npm run tokens`.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(await readFile(resolve(root, "design/tokens.json"), "utf8"));
const outFile = resolve(root, "src/styles/tokens.css");

const comment = (text) => `/* ${text.replaceAll("*/", "* /")} */`;
const indent = (lines, depth = 1) => lines.map((l) => (l ? "  ".repeat(depth) + l : l)).join("\n");

const colors = tokens.color.tokens;
const lightVars = colors.flatMap((t) => [comment(t.usage), `--${t.name}: ${t.value.light};`]);
const darkVars = colors.map((t) => `--${t.name}: ${t.value.dark};`);

const typeStyles = tokens.type.groups.flatMap((group) =>
  group.styles.map((style) => ({ ...style, family: group.family })),
);

const theme = [
  ...colors.map((t) => `--color-${t.name}: var(--${t.name});`),
  "",
  ...Object.keys(tokens.type.families).map((f) => `--font-${f}: var(--font-${f}-loaded), ${tokens.type.families[f]};`),
  "",
  ...typeStyles.flatMap((s) => [
    `--text-${s.name}: ${s.fontSize};`,
    `--text-${s.name}--line-height: ${s.lineHeight};`,
    `--text-${s.name}--font-weight: ${s.fontWeight};`,
  ]),
  "",
  ...tokens.spacing.tokens.flatMap((t) => [comment(t.usage), `--spacing-${t.name.replace("space-", "")}: ${t.value};`]),
  "",
  ...tokens.radius.tokens.flatMap((t) => [comment(t.usage), `--radius-${t.name.replace("radius-", "")}: ${t.value};`]),
  "",
  ...tokens.shadow.tokens.flatMap((t) => [comment(t.usage), `--shadow-${t.name.replace("shadow-", "")}: ${t.value};`]),
];

const css = `/* Generated by scripts/build-tokens.mjs from design/tokens.json. Do not edit by hand. */

:root {
${indent(lightVars)}
}

/* Night theme: explicit choice, or Auto following the system setting. */
:root[data-theme="night"] {
${indent(darkVars)}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="day"]):not([data-theme="night"]) {
${indent(darkVars, 2)}
  }
}

@theme inline {
${indent(theme)}
}
`;

await mkdir(dirname(outFile), { recursive: true });
await writeFile(outFile, css);
console.log(`Wrote ${outFile}`);
